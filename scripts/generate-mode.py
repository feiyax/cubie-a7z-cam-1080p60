#!/usr/bin/env python3
"""Extract Intel's complete binned mode with explicit local timing controls."""
import pathlib, re, argparse
p=argparse.ArgumentParser();p.add_argument("--output",type=pathlib.Path,required=True);p.add_argument("--link-mbps",type=int,choices=[1080,1200],default=1080)
opts=p.parse_args();vts={1080:1438,1200:1598}[opts.link_mbps];pclk=opts.link_mbps*400000
exposure=round(.010*pclk/5008)
root = pathlib.Path(__file__).resolve().parents[1]
text = (root/'upstream/intel/crl_imx214_configuration.h').read_text()
def table(name):
    body = re.search(r'\b'+name+r'\[\] = \{(.*?)\n\};', text, re.S)[1]
    return [(int(a,16),int(v,16)) for a,v in re.findall(
        r'\{\s*(0x[0-9a-fA-F]+),\s*CRL_REG_LEN_08BIT,\s*(0x[0-9a-fA-F]+)\s*\}',body)]
regs = []
for a,v in table('imx214_powerup_regset'):
    regs.append((a,3 if a==0x0101 else v)) # Existing board orientation/BGGR.
    if a==0x0103: regs.append((0xffff,5)) # Reset settling before next write.
regs += table(f'imx214_pll_{opts.link_mbps}mbps')
regs += table('imx214_mode_1080') # Intel writes mode after PLL; order matters.
# Keep the validated board crop: 3840x2160 -> true 2x2 -> 1920x1080.
crop = {0x0344:0,0x0345:0xb8,0x0346:1,0x0347:0xe0,
        0x0348:0xf,0x0349:0xb7,0x034a:0xa,0x034b:0x4f}
regs = [(a,crop.get(a,v)) for a,v in regs]
regs += [(0x0112,0x0a),(0x0113,0x0a),
         (0x0342,0x13),(0x0343,0x90), # 5008 line clocks
         (0x0340,vts>>8),(0x0341,vts&255), # Selected frame length; see generated constants
         (0x0202,exposure>>8),(0x0203,exposure&255), # Approximately10ms initial integration
         (0x0204,0),(0x0205,0)]
out = '''/* SPDX-License-Identifier: GPL-2.0-only */
/* Copyright (c) 2014--2016 Intel Corporation.
 * Author: Vinod Govindapillai.
 * Intel camera drivers f06e5fc31eb36edb15118cd04b29c53b56dc126a.
 * Source: drivers/media/i2c/crlmodule/crl_imx214_configuration.h (GPL-2.0).
 * Complete powerup -> selected RAW10 PLL -> 2x2-binned 1920x1080 mode.
 * Local changes: board flip=3 and centered3840x2160 crop, 5ms reset delay,
 * explicit RAW10, HTS5008,
 * Selected VTS and approximately10ms initial exposure; unity analog gain.
 * Generated by scripts/generate-mode.py; no sensor stream-on in table.
 */
static const struct regval_list sensor_1080p60_regs[] = {
'''
out = out.replace('static const struct regval_list', f'#define IMX214_60_VTS {vts}U\n#define IMX214_60_PCLK {pclk}U\n#define IMX214_60_MIPI_BPS {opts.link_mbps*1000000}U\nstatic const struct regval_list')
out += ''.join(f'\t{{0x{a:04x}, 0x{v:02x}}},\n' for a,v in regs)
out += '};\n'
opts.output.parent.mkdir(parents=True,exist_ok=True)
opts.output.write_text(out)
